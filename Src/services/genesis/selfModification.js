/**
 * GENESIS SELF-MODIFICATION ENGINE
 *
 * Generates new code following Phoenix patterns.
 * This is how Genesis writes its own capabilities.
 */

const codeConsciousness = require('./codeConsciousness');

class SelfModificationEngine {
    constructor() {
        this.templates = new Map();
        this.initializeTemplates();
    }

    /**
     * Initialize code templates
     */
    initializeTemplates() {
        // Mongoose Model Template
        this.templates.set('mongoose-model', (name, domain, fields) => `
const mongoose = require('mongoose');

const ${name}Schema = new mongoose.Schema({
${fields.map(f => `    ${f.name}: { type: ${f.type}, ${f.required ? 'required: true' : ''} }`).join(',\n')}
}, {
    timestamps: true
});

module.exports = mongoose.model('${name}', ${name}Schema);
`);

        // Service Template
        this.templates.set('service', (name, domain, model) => `
/**
 * ${name} Service
 * Auto-generated by Genesis
 */

const ${model} = require('../../models/${domain}/${model}');

class ${name}Service {
    /**
     * Create new ${model.toLowerCase()}
     */
    async create(userId, data) {
        try {
            const item = new ${model}({
                userId,
                ...data
            });
            await item.save();
            return { success: true, data: item };
        } catch (error) {
            return { success: false, error: error.message };
        }
    }

    /**
     * Get all ${model.toLowerCase()}s for user
     */
    async getAll(userId) {
        try {
            const items = await ${model}.find({ userId }).sort({ createdAt: -1 });
            return { success: true, data: items };
        } catch (error) {
            return { success: false, error: error.message };
        }
    }

    /**
     * Get single ${model.toLowerCase()} by ID
     */
    async getById(userId, id) {
        try {
            const item = await ${model}.findOne({ _id: id, userId });
            if (!item) {
                return { success: false, error: '${model} not found' };
            }
            return { success: true, data: item };
        } catch (error) {
            return { success: false, error: error.message };
        }
    }

    /**
     * Update ${model.toLowerCase()}
     */
    async update(userId, id, updates) {
        try {
            const item = await ${model}.findOneAndUpdate(
                { _id: id, userId },
                updates,
                { new: true }
            );
            if (!item) {
                return { success: false, error: '${model} not found' };
            }
            return { success: true, data: item };
        } catch (error) {
            return { success: false, error: error.message };
        }
    }

    /**
     * Delete ${model.toLowerCase()}
     */
    async delete(userId, id) {
        try {
            const item = await ${model}.findOneAndDelete({ _id: id, userId });
            if (!item) {
                return { success: false, error: '${model} not found' };
            }
            return { success: true };
        } catch (error) {
            return { success: false, error: error.message };
        }
    }
}

module.exports = new ${name}Service();
`);

        // Express Route Template
        this.templates.set('route', (name, domain, serviceName) => `
/**
 * ${name} Routes
 * Auto-generated by Genesis
 */

const express = require('express');
const router = express.Router();
const auth = require('../../middleware/auth');
const ${serviceName} = require('../services/${domain}/${serviceName}');

/**
 * Create new item
 */
router.post('/', auth, async (req, res) => {
    try {
        const result = await ${serviceName}.create(req.user.id, req.body);
        if (!result.success) {
            return res.status(400).json(result);
        }
        res.status(201).json(result);
    } catch (error) {
        res.status(500).json({ success: false, error: error.message });
    }
});

/**
 * Get all items
 */
router.get('/', auth, async (req, res) => {
    try {
        const result = await ${serviceName}.getAll(req.user.id);
        res.json(result);
    } catch (error) {
        res.status(500).json({ success: false, error: error.message });
    }
});

/**
 * Get single item
 */
router.get('/:id', auth, async (req, res) => {
    try {
        const result = await ${serviceName}.getById(req.user.id, req.params.id);
        if (!result.success) {
            return res.status(404).json(result);
        }
        res.json(result);
    } catch (error) {
        res.status(500).json({ success: false, error: error.message });
    }
});

/**
 * Update item
 */
router.put('/:id', auth, async (req, res) => {
    try {
        const result = await ${serviceName}.update(req.user.id, req.params.id, req.body);
        if (!result.success) {
            return res.status(404).json(result);
        }
        res.json(result);
    } catch (error) {
        res.status(500).json({ success: false, error: error.message });
    }
});

/**
 * Delete item
 */
router.delete('/:id', auth, async (req, res) => {
    try {
        const result = await ${serviceName}.delete(req.user.id, req.params.id);
        if (!result.success) {
            return res.status(404).json(result);
        }
        res.json(result);
    } catch (error) {
        res.status(500).json({ success: false, error: error.message });
    }
});

module.exports = router;
`);

        // Frontend Widget Template
        this.templates.set('widget', (name, domain, apiEndpoint) => `
/**
 * ${name} Widget
 * Auto-generated by Genesis
 */

class ${name}Widget {
    constructor(containerId) {
        this.containerId = containerId;
        this.container = document.getElementById(containerId);
        this.data = [];
        this.init();
    }

    async init() {
        await this.loadData();
        this.render();
        this.attachEventListeners();
    }

    async loadData() {
        try {
            const token = localStorage.getItem('phoenixToken');
            const baseUrl = window.PhoenixConfig?.API_BASE_URL || 'https://pal-backend-production.up.railway.app/api';

            const response = await fetch(\`\${baseUrl}${apiEndpoint}\`, {
                headers: {
                    'Authorization': \`Bearer \${token}\`
                }
            });

            const result = await response.json();
            if (result.success) {
                this.data = result.data;
            }
        } catch (error) {
            console.error('Error loading ${name} data:', error);
        }
    }

    render() {
        if (!this.container) return;

        this.container.innerHTML = \`
            <div class="genesis-widget" style="
                background: linear-gradient(135deg, #1a1a2e 0%, #16213e 100%);
                border: 2px solid #0f4c75;
                border-radius: 20px;
                padding: 24px;
                color: #fff;
            ">
                <h2 style="margin: 0 0 20px 0; color: #00d9ff;">${name}</h2>
                <div id="${name}-content">
                    \${this.renderContent()}
                </div>
            </div>
        \`;
    }

    renderContent() {
        if (this.data.length === 0) {
            return '<p style="opacity: 0.6;">No data yet. Start tracking!</p>';
        }

        return this.data.map(item => \`
            <div style="
                background: rgba(255,255,255,0.05);
                padding: 16px;
                border-radius: 12px;
                margin-bottom: 12px;
            ">
                <pre>\${JSON.stringify(item, null, 2)}</pre>
            </div>
        \`).join('');
    }

    attachEventListeners() {
        // Add event listeners here
    }

    async refresh() {
        await this.loadData();
        this.render();
    }
}

window.${name}Widget = ${name}Widget;
`);
    }

    /**
     * Generate code from natural language request
     */
    async generateFromRequest(request) {
        console.log('[Genesis] Generating code from request:', request);

        // Parse the request to understand intent
        const intent = this.parseIntent(request);
        console.log('[Genesis] Parsed intent:', intent);

        // Generate appropriate code
        const code = await this.generateCode(intent);

        return {
            success: true,
            intent,
            code,
            files: Object.keys(code)
        };
    }

    /**
     * Parse natural language to intent
     */
    parseIntent(request) {
        const lower = request.toLowerCase();

        // Detect domain (mercury, venus, mars, jupiter, etc.)
        const domains = ['mercury', 'venus', 'earth', 'mars', 'jupiter', 'saturn', 'uranus', 'neptune'];
        let domain = 'custom';
        for (const d of domains) {
            if (lower.includes(d)) {
                domain = d;
                break;
            }
        }

        // Detect type (tracker, planner, analyzer, etc.)
        let type = 'tracker';
        if (lower.includes('plan')) type = 'planner';
        if (lower.includes('analy')) type = 'analyzer';
        if (lower.includes('track')) type = 'tracker';

        // Extract entity name
        const words = request.split(' ');
        const entityName = words.find(w => w.length > 3 && !domains.includes(w.toLowerCase())) || 'Custom';

        return {
            domain,
            type,
            entityName,
            fullRequest: request
        };
    }

    /**
     * Generate actual code files
     */
    async generateCode(intent) {
        const { domain, type, entityName } = intent;
        const modelName = `${entityName}`;
        const serviceName = `${entityName}Service`;

        const code = {};

        // Generate Model
        code[`models/${domain}/${modelName}.js`] = this.templates.get('mongoose-model')(
            modelName,
            domain,
            [
                { name: 'userId', type: 'mongoose.Schema.Types.ObjectId', required: true },
                { name: 'name', type: 'String', required: true },
                { name: 'data', type: 'mongoose.Schema.Types.Mixed', required: false }
            ]
        );

        // Generate Service
        code[`services/${domain}/${serviceName}.js`] = this.templates.get('service')(
            serviceName,
            domain,
            modelName
        );

        // Generate Routes
        code[`routes/${domain}/${type}.js`] = this.templates.get('route')(
            `${entityName} Routes`,
            domain,
            serviceName
        );

        // Generate Widget
        code[`widgets/${entityName}Widget.js`] = this.templates.get('widget')(
            entityName,
            domain,
            `/${domain}/${type}`
        );

        return code;
    }
}

module.exports = new SelfModificationEngine();
